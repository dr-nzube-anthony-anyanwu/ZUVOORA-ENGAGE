"""Private object storage for original knowledge uploads (Phase 2c, ADR-023).

Objects are written with the server-side secret key to a private bucket that has no access
policies, so browsers can never read them. Paths are generated by the database from
tenant/document/version ids; this client never accepts user-supplied paths. Objects are stored
as opaque bytes (`application/octet-stream`) and never overwritten.
"""

from __future__ import annotations

import re
from typing import Protocol

import httpx

from app.config import Settings

BUCKET = "knowledge-originals"
_PATH = re.compile(r"^[0-9a-f-]{36}/[0-9a-f-]{36}/[0-9a-f-]{36}$")


class StorageError(Exception):
    pass


class ObjectStore(Protocol):
    def put(self, path: str, data: bytes) -> None: ...


class SupabaseObjectStore:
    def __init__(self, settings: Settings) -> None:
        if not settings.supabase_url or settings.supabase_secret_key is None:
            raise ValueError("Supabase URL and secret key are required for storage")
        self._base = f"{settings.supabase_url}/storage/v1/object/{BUCKET}"
        key = settings.supabase_secret_key.get_secret_value()
        self._headers = {"apikey": key, "Authorization": f"Bearer {key}"}

    def put(self, path: str, data: bytes) -> None:
        if not _PATH.match(path):  # defence in depth: only database-generated paths
            raise StorageError("invalid object path")
        try:
            response = httpx.post(
                f"{self._base}/{path}",
                headers={**self._headers, "Content-Type": "application/octet-stream",
                         "x-upsert": "false", "Cache-Control": "no-store"},
                content=data,
                timeout=30,
            )
        except httpx.HTTPError as exc:
            raise StorageError("storage request failed") from exc
        if response.status_code not in (200, 201):
            raise StorageError(f"storage rejected upload ({response.status_code})")
