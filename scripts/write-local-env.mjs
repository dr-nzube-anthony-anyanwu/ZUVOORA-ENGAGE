#!/usr/bin/env node
/**
 * Writes LOCAL development env files from the running local Supabase stack:
 *   apps/api/.env        (server: local secret key, engage_api DB URL)
 *   apps/web/.env.local  (browser-safe: URL + publishable key; server-only API URL)
 *
 * Safety: refuses to run unless Supabase is on localhost, never overwrites existing files,
 * and never prints key values. Cloud/staging values must be entered by hand, never by script.
 */
import { execFileSync } from "node:child_process";
import { randomBytes } from "node:crypto";
import { existsSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = fileURLToPath(new URL("..", import.meta.url));
// Run the pinned, locally installed CLI through Node directly (no shell involved).
const supabaseCli = join(ROOT, "node_modules", "supabase", "dist", "supabase.js");

let status;
try {
  status = JSON.parse(
    execFileSync(process.execPath, [supabaseCli, "status", "-o", "json"], {
      cwd: ROOT,
      encoding: "utf8",
      stdio: ["ignore", "pipe", "ignore"],
    }),
  );
} catch {
  console.error("Local Supabase is not running. Start it with: npm run db:start");
  process.exit(1);
}

const apiUrl = status.API_URL;
if (!/^http:\/\/(127\.0\.0\.1|localhost):\d+$/.test(apiUrl ?? "")) {
  console.error("Refusing: Supabase API_URL is not a localhost URL.");
  process.exit(1);
}
const dbHost = String(status.DB_URL).split("@")[1];

const files = {
  [join(ROOT, "apps", "api", ".env")]: [
    "# LOCAL DEVELOPMENT ONLY — generated by scripts/write-local-env.mjs. Do not commit.",
    "APP_ENV=development",
    "API_CORS_ORIGINS=http://localhost:3073",
    "DASHBOARD_URL=http://localhost:3073",
    `SUPABASE_URL=${apiUrl}`,
    `SUPABASE_SECRET_KEY=${status.SECRET_KEY}`,
    `DATABASE_URL=postgresql://engage_api:local-dev-only-engage-api@${dbHost}`,
    `WIDGET_TOKEN_SECRET=${randomBytes(48).toString("base64url")}`,
    "WIDGET_ALLOW_HTTP_FRAMES=true",
    "",
  ],
  [join(ROOT, "apps", "web", ".env.local")]: [
    "# LOCAL DEVELOPMENT ONLY — generated by scripts/write-local-env.mjs. Do not commit.",
    `NEXT_PUBLIC_SUPABASE_URL=${apiUrl}`,
    `NEXT_PUBLIC_SUPABASE_PUBLISHABLE_KEY=${status.PUBLISHABLE_KEY}`,
    "ENGAGE_API_URL=http://127.0.0.1:8073",
    "",
  ],
};

for (const [path, lines] of Object.entries(files)) {
  if (existsSync(path)) {
    console.log(`skipped (already exists): ${path}`);
    continue;
  }
  writeFileSync(path, lines.join("\n"), { encoding: "utf8", flag: "wx" });
  console.log(`written: ${path}`);
}
